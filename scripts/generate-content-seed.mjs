/**
 * Emits the INSERT half of the editable-content migration from
 * lib/content/defaults.ts.
 *
 *   node scripts/generate-content-seed.mjs > supabase/seed-content.generated.sql
 *
 * The seed is generated rather than hand-written because it is a copy of forty
 * settings, seven headings, twenty-six services and thirty-two image URLs. Any
 * of those transcribed by hand would eventually disagree with the defaults the
 * site falls back to, and the disagreement would only show up as a section
 * that changes when the database happens to be reachable. Generating it means
 * the two are the same data by construction.
 *
 * Every statement is an upsert on the row's stable id, so re-running the
 * migration refreshes the seeded rows without duplicating them — and without
 * touching any row an editor has added.
 *
 * This reads the defaults through a tiny hand-rolled parse of the TypeScript
 * module rather than importing it, because the module is TypeScript with a
 * path alias and this script runs under plain node. See `loadDefaults`.
 */

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Reads lib/content/defaults.ts by stripping the import and the type
 * annotation and evaluating the remaining object literal.
 *
 * The alternative — a TypeScript loader in devDependencies purely to run one
 * build script — is a heavier dependency than the problem deserves. The
 * transformation is two regexes because the module is deliberately a single
 * plain object literal with no computed values, and it will fail loudly rather
 * than silently if that ever stops being true.
 */
function loadDefaults() {
  const source = readFileSync(join(root, "lib/content/defaults.ts"), "utf8");

  const start = source.indexOf("export const defaultContent");
  if (start === -1) throw new Error("defaults.ts no longer exports defaultContent");

  const literalStart = source.indexOf("{", start);
  const literal = source.slice(literalStart, source.lastIndexOf("};") + 1);

  // eslint-disable-next-line no-new-func
  return new Function(`return ${literal}`)();
}

/** Single-quoted SQL literal; doubles any embedded quote. */
const q = (value) => `'${String(value).replace(/'/g, "''")}'`;
const nullable = (value) => (value === null || value === undefined ? "NULL" : q(value));

function upsert(table, columns, rows, conflictColumn = "id") {
  if (rows.length === 0) return "";

  const updates = columns
    .filter((column) => column !== conflictColumn)
    .map((column) => `${column} = EXCLUDED.${column}`)
    .join(",\n    ");

  const values = rows
    .map((row) => `  (${columns.map((column) => row[column]).join(", ")})`)
    .join(",\n");

  return [
    `INSERT INTO public.${table} (${columns.join(", ")}) VALUES`,
    values,
    `ON CONFLICT (${conflictColumn}) DO UPDATE SET`,
    `    ${updates};`,
    "",
  ].join("\n");
}

const content = loadDefaults();
const out = [];

out.push("-- Generated by scripts/generate-content-seed.mjs — do not edit by hand.");
out.push("-- Re-run it after changing lib/content/defaults.ts.");
out.push("");

out.push(
  upsert(
    "site_settings",
    ["key", "value"],
    Object.entries(content.settings).map(([key, value]) => ({
      key: q(key),
      value: q(value),
    })),
    "key"
  )
);

out.push(
  upsert(
    "section_headings",
    ["section", "eyebrow", "title", "subtitle"],
    Object.values(content.headings).map((heading) => ({
      section: q(heading.section),
      eyebrow: q(heading.eyebrow),
      title: q(heading.title),
      subtitle: nullable(heading.subtitle),
    })),
    "section"
  )
);

const listed = (row) => ({ id: q(row.id), sort_order: row.sort_order });

out.push(
  upsert("service_groups", ["id", "slug", "label", "sort_order"],
    content.serviceGroups.map((row) => ({ ...listed(row), slug: q(row.slug), label: q(row.label) })))
);

out.push(
  upsert("services", ["id", "group_slug", "icon", "title", "description", "sort_order"],
    content.services.map((row) => ({
      ...listed(row), group_slug: q(row.group_slug), icon: q(row.icon),
      title: q(row.title), description: q(row.description),
    })))
);

out.push(
  upsert("about_features", ["id", "icon", "title", "description", "sort_order"],
    content.aboutFeatures.map((row) => ({
      ...listed(row), icon: q(row.icon), title: q(row.title), description: q(row.description),
    })))
);

out.push(
  upsert("process_steps", ["id", "icon", "title", "description", "sort_order"],
    content.processSteps.map((row) => ({
      ...listed(row), icon: q(row.icon), title: q(row.title), description: q(row.description),
    })))
);

out.push(
  upsert("stats", ["id", "emoji", "target", "suffix", "label", "sort_order"],
    content.stats.map((row) => ({
      ...listed(row), emoji: q(row.emoji), target: row.target,
      suffix: q(row.suffix), label: q(row.label),
    })))
);

out.push(
  upsert("faqs", ["id", "question", "answer", "sort_order"],
    content.faqs.map((row) => ({
      ...listed(row), question: q(row.question), answer: q(row.answer),
    })))
);

out.push(
  upsert("design_categories", ["id", "slug", "label", "sort_order"],
    content.designCategories.map((row) => ({ ...listed(row), slug: q(row.slug), label: q(row.label) })))
);

out.push(
  upsert("design_images", ["id", "category_slug", "image_url", "sort_order"],
    content.designImages.map((row) => ({
      ...listed(row), category_slug: q(row.category_slug), image_url: q(row.image_url),
    })))
);

out.push(
  upsert("before_after", ["id", "title", "before_image", "after_image", "sort_order"],
    content.beforeAfter.map((row) => ({
      ...listed(row), title: q(row.title),
      before_image: q(row.before_image), after_image: q(row.after_image),
    })))
);

out.push(
  upsert("service_options", ["id", "label", "sort_order"],
    content.serviceOptions.map((row) => ({ ...listed(row), label: q(row.label) })))
);

process.stdout.write(out.join("\n"));
